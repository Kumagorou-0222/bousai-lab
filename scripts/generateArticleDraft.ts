/**
 * 記事下書き自動生成スクリプト
 *
 * 必須環境変数:
 *   ANTHROPIC_API_KEY — Claude API キー
 *
 * 実行例:
 *   npx tsx scripts/generateArticleDraft.ts
 *   npx tsx scripts/generateArticleDraft.ts --slug blackout-smartphone-battery
 *   npx tsx scripts/generateArticleDraft.ts --force     # 既存下書きを上書き
 *   npx tsx scripts/generateArticleDraft.ts --limit 1   # 未生成のアイデアから1件だけ生成（毎日の自動実行用）
 */

import fs from 'fs'
import path from 'path'
import Anthropic from '@anthropic-ai/sdk'
import matter from 'gray-matter'
import type { ArticleIdea } from '../lib/draftUtils'
import { DRAFTS_DIR, getAllDraftSlugs } from '../lib/draftUtils'
import { getAllSlugs } from '../lib/articles'

// =====================================================
// 定数
// =====================================================

const IDEAS_PATH = path.join(process.cwd(), 'data', 'article-ideas.json')

// =====================================================
// Claude API
// =====================================================

function initClient(): Anthropic {
  const key = process.env.ANTHROPIC_API_KEY
  if (!key) throw new Error('ANTHROPIC_API_KEY が未設定です')
  return new Anthropic({ apiKey: key })
}

// =====================================================
// 既存スラッグ一覧（relatedSlugs 付与用）
// =====================================================

function getSameCategoryRelated(category: string, currentSlug: string): string[] {
  try {
    const all = getAllSlugs()
    const same = all.filter((s) => {
      try {
        const raw = fs.readFileSync(
          path.join(process.cwd(), 'content', 'articles', `${s}.mdx`),
          'utf-8',
        )
        const { data } = matter(raw)
        return data.category === category && s !== currentSlug
      } catch {
        return false
      }
    })
    return same.slice(0, 4)
  } catch {
    return []
  }
}

