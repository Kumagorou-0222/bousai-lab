// =====================================================
// MDX ファイル生成
// =====================================================

type GeneratedData = {
  frontmatter: Record<string, unknown>
  body: string
}

function buildMdxContent(idea: ArticleIdea, generated: GeneratedData): string {
  const fm = generated.frontmatter
  const today = new Date().toISOString().slice(0, 10)

  const data: Record<string, unknown> = {
    title: fm.title,
    description: fm.description,
    category: idea.category,
    date: today,
    emoji: fm.emoji,
    status: 'draft',
    reviewRequired: true,
    autoGenerated: true,
    conclusion: fm.conclusion,
    reasons: fm.reasons,
    manga: fm.manga,
    faqs: fm.faqs,
    relatedSlugs: fm.relatedSlugs,
    monetizeItems: fm.monetizeItems,
    region: fm.region,
    xSeries: idea.xSeries,
    mangaPrompt: fm.mangaPrompt,
  }

  return matter.stringify(generated.body ?? '', data)
}

// =====================================================
// メイン
// =====================================================

async function main(): Promise<void> {
  const args = process.argv.slice(2)
  const force = args.includes('--force')
  const slugIndex = args.indexOf('--slug')
  const targetSlug = slugIndex >= 0 ? args[slugIndex + 1] : null
  const limitIndex = args.indexOf('--limit')
  const limit = limitIndex >= 0 ? parseInt(args[limitIndex + 1], 10) : Infinity

  const client = initClient()

  const ideas: ArticleIdea[] = JSON.parse(fs.readFileSync(IDEAS_PATH, 'utf-8'))
  const existingDrafts = new Set(getAllDraftSlugs())
  const publishedSlugs = new Set(getAllSlugs())

  if (!fs.existsSync(DRAFTS_DIR)) fs.mkdirSync(DRAFTS_DIR, { recursive: true })

  const targets = ideas.filter((idea) => {
    if (targetSlug && idea.slug !== targetSlug) return false
    if (!force && publishedSlugs.has(idea.slug)) {
      console.log(`[skip] ${idea.slug} — 公開済み記事あり`)
      return false
    }
    if (!force && existingDrafts.has(idea.slug)) {
      console.log(`[skip] ${idea.slug} — 既存の下書きあり（--force で上書き可）`)
      return false
    }
    return true
  }).slice(0, limit)

  if (targets.length === 0) {
    console.log('生成対象がありません。')
    return
  }

  console.log(`\n生成対象: ${targets.length} 件\n`)

  for (const idea of targets) {
    console.log(`\n━━━ [${idea.slug}] 生成中 ━━━`)
    console.log(`タイトル: ${idea.title}`)

    const relatedSlugs = getSameCategoryRelated(idea.category, idea.slug)

    let generated: GeneratedData | null = null
    let attempt = 0

    while (attempt < 3 && !generated) {
      attempt++
      try {
        console.log(`  Claude API 呼び出し (attempt ${attempt})...`)
        const res = await client.messages.create({
          model: 'claude-sonnet-4-6',
          max_tokens: 4096,
          system: SYSTEM_PROMPT,
          messages: [{ role: 'user', content: buildUserPrompt(idea, relatedSlugs) }],
        })

        const text = res.content[0].type === 'text' ? res.content[0].text : ''
        const cleaned = text.replace(/^```json\s*/i, '').replace(/\s*```$/, '').trim()
        generated = JSON.parse(cleaned) as GeneratedData
        console.log(`  JSON パース成功`)
      } catch (e) {
        console.warn(`  attempt ${attempt} 失敗:`, e instanceof Error ? e.message : e)
        if (attempt >= 3) throw e
      }
    }

    if (!generated) throw new Error(`${idea.slug} の生成に失敗しました`)

    const mdxContent = buildMdxContent(idea, generated)
    const outPath = path.join(DRAFTS_DIR, `${idea.slug}.mdx`)
    fs.writeFileSync(outPath, mdxContent, 'utf-8')
    console.log(`  保存: content/drafts/${idea.slug}.mdx`)
  }

  console.log('\n✅ 生成完了\n')
}

main().catch((err) => {
  console.error('❌ エラー:', err)
  process.exit(1)
})
