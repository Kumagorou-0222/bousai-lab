def get_emergency_advice(full_text: str) -> list[str]:
    """
    災害情報の内容から、即座に取るべき行動（医師監修）を3-4項目返す
    """
    text = full_text.lower()
    
    # 地震
    if any(kw in text for kw in ["地震", "震度", "揺れ"]):
        return [
            "頭を保護し、丈夫な机の下に隠れる",
            "火の元を確認し、揺れが収まるまで待つ",
            "出口を確保し、倒れやすい家具から離れる",
            "エレベーターは絶対に使用しない"
        ]
    
    # 津波
    if any(kw in text for kw in ["津波"]):
        return [
            "直ちに海岸から離れ、高台へ避難する",
            "「遠く」よりも「高く」へ避難を優先",
            "警報が解除されるまで絶対に戻らない",
            "車での避難は渋滞に巻き込まれる恐れあり"
        ]
    
    # 大雨・洪水・氾濫
    if any(kw in text for kw in ["大雨", "洪水", "氾濫", "浸水"]):
        return [
            "浸水が始まる前に、頑丈な建物の2階以上へ",
            "垂直避難（高い場所への移動）を検討",
            "マンホールや側溝は水で見えなくなり危険",
            "断水に備え、飲料水とトイレの確保を"
        ]
    
    # 台風・暴風
    if any(kw in text for kw in ["台風", "暴風"]):
        return [
            "屋外での作業は絶対にやめる",
            "窓ガラスから離れ、カーテンを閉める",
            "停電に備え、スマホの充電と懐中電灯を",
            "飛来物に注意し、外出を控える"
        ]
    
    # 火山
    if any(kw in text for kw in ["火山", "噴火"]):
        return [
            "ヘルメットや帽子で頭を守る",
            "マスクや濡れタオルで灰の吸入を防ぐ",
            "避難時はゴーグル等で目を保護する",
            "最新の噴火情報を常に確認する"
        ]
        
    # デフォルト
    return [
        "落ち着いて周囲の状況を確認する",
        "最新の公式情報をラジオやネットで入手",
        "家族や周囲と声を掛け合い避難を検討",
        "非常持ち出し袋をすぐに持てる場所に"
    ]
